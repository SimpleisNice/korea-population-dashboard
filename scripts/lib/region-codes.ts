/**
 * 분할된 지역의 승계 관계 (구 코드 → 신 코드들)
 *
 * 인천 2026.07.01 개편은 3개 구를 4개로 재편한 **분할**이라 1:1 병합이 성립하지 않는다.
 *   중구 + 동구 → 제물포구 + 영종구
 *   서구        → 서해구 + 검단구
 *
 * 과거 인구를 신 지역에 배분할 근거가 없으므로 병합하지 않는다. 대신 구 지역은
 * 개편월 이전 이력을 그대로 보존하고(사용자가 과거를 조회할 수 있어야 한다),
 * 지역 페이지에 폐지 사실과 승계 지역을 표기해 왜 최신 데이터가 없는지 알린다.
 * 최신월 데이터가 없으므로 순위·전국 합계에서는 기존 무폴백 규칙에 의해 자동 제외된다.
 */
